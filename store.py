"""Database layer.  SQLite by default (file in DATA_DIR) - or PostgreSQL / Supabase when DATABASE_URL is set.
Both use the same SQL (placeholders '?', ON CONFLICT upserts); this class adapts the small differences."""
import os, re, json, sqlite3, threading, time
from pathlib import Path

TABLES = ("users", "lessons", "progress", "settings")


class Store:
    def __init__(self, data_dir):
        self.url = os.environ.get("DATABASE_URL", "").strip()
        self.pg = self.url.startswith(("postgres://", "postgresql://"))
        self.lock = threading.RLock()
        self.conn = None
        self.path = Path(data_dir) / "app.db"
        self._connect()
        self._schema()

    # ------------------------------------------------------------ connection
    def _connect(self):
        if self.pg:
            import psycopg2, psycopg2.extras                      # pip install psycopg2-binary
            url = self.url.replace("postgres://", "postgresql://", 1)
            kw = {"connect_timeout": 10, "cursor_factory": psycopg2.extras.RealDictCursor}
            if "sslmode" not in url and not re.search(r"@(localhost|127\.0\.0\.1)", url): kw["sslmode"] = "require"   # Supabase needs SSL
            self.conn = psycopg2.connect(url, **kw)
            self.conn.autocommit = True
        else:
            self.conn = sqlite3.connect(str(self.path), check_same_thread=False, isolation_level=None)
            self.conn.row_factory = sqlite3.Row
            self.conn.execute("PRAGMA journal_mode=WAL"); self.conn.execute("PRAGMA foreign_keys=ON")

    def _sql(self, sql): return sql.replace("?", "%s") if self.pg else sql

    def _exec(self, sql, args=()):
        with self.lock:
            for attempt in (0, 1):
                try:
                    if self.pg:
                        cur = self.conn.cursor(); cur.execute(self._sql(sql), args); return cur
                    return self.conn.execute(sql, args)
                except Exception as e:
                    # Supabase / poolers drop idle connections: reconnect once and retry
                    if self.pg and attempt == 0 and e.__class__.__name__ in ("OperationalError", "InterfaceError"):
                        try: self.conn.close()
                        except Exception: pass
                        time.sleep(0.3); self._connect(); continue
                    raise

    def run(self, sql, args=()):
        cur = self._exec(sql, args); n = cur.rowcount
        if self.pg: cur.close()
        return n

    def all(self, sql, args=()):
        cur = self._exec(sql, args); rows = cur.fetchall()
        if self.pg: cur.close()
        return rows

    def one(self, sql, args=()):
        cur = self._exec(sql, args); row = cur.fetchone()
        if self.pg: cur.close()
        return row

    def insert_id(self, sql, args=()):
        """INSERT ... and return the new row id (works on both databases)."""
        with self.lock:
            if self.pg:
                cur = self._exec(sql + " RETURNING id", args); rid = cur.fetchone()["id"]; cur.close(); return rid
            return self._exec(sql, args).lastrowid

    # ------------------------------------------------------------ schema
    def _schema(self):
        pk = "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" if self.pg else "INTEGER PRIMARY KEY AUTOINCREMENT"
        real, big = ("DOUBLE PRECISION", "BIGINT") if self.pg else ("REAL", "INTEGER")
        stmts = [
            f"CREATE TABLE IF NOT EXISTS users(id {pk}, username TEXT NOT NULL, username_lc TEXT UNIQUE, password_hash TEXT NOT NULL, "
            f"is_admin INTEGER NOT NULL DEFAULT 0, role TEXT NOT NULL DEFAULT 'student', disabled INTEGER NOT NULL DEFAULT 0, created {real}, data TEXT NOT NULL DEFAULT '{{}}')",
            f"CREATE TABLE IF NOT EXISTS lessons(id TEXT PRIMARY KEY, user_id {big} NOT NULL REFERENCES users(id) ON DELETE CASCADE, title TEXT, created {real}, "
            "course TEXT NOT NULL, notes TEXT DEFAULT '', shared TEXT NOT NULL DEFAULT '[]', shared_all INTEGER NOT NULL DEFAULT 0)",
            f"CREATE TABLE IF NOT EXISTS progress(user_id {big} NOT NULL REFERENCES users(id) ON DELETE CASCADE, lesson_id TEXT NOT NULL, data TEXT NOT NULL, PRIMARY KEY(user_id, lesson_id))",
            "CREATE TABLE IF NOT EXISTS settings(key TEXT PRIMARY KEY, value TEXT)"]
        for s in stmts: self.run(s)
        if self.pg:
            for t in TABLES:                                    # Supabase exposes tables through its REST API: lock it (this app connects as owner and bypasses RLS)
                try: self.run(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY")
                except Exception: pass
            self._maybe_import_sqlite()
        else:
            cols = {r["name"] for r in self.all("PRAGMA table_info(users)")}          # upgrade databases made by the previous version
            if "username_lc" not in cols:
                self.run("ALTER TABLE users ADD COLUMN username_lc TEXT"); self.run("UPDATE users SET username_lc=lower(username)")
            if "role" not in cols:
                self.run("ALTER TABLE users ADD COLUMN role TEXT NOT NULL DEFAULT 'student'"); self.run("UPDATE users SET role='admin' WHERE is_admin=1")
            self.run("CREATE UNIQUE INDEX IF NOT EXISTS idx_users_lc ON users(username_lc)")

    # ------------------------------------------------------------ one-time copy: local SQLite -> Supabase
    def _maybe_import_sqlite(self):
        try:
            if self.one("SELECT 1 FROM users LIMIT 1") or not self.path.exists(): return
            src = sqlite3.connect(str(self.path)); src.row_factory = sqlite3.Row
            if not src.execute("SELECT 1 FROM users LIMIT 1").fetchone(): return
            cols = {t: [r[1] for r in src.execute(f"PRAGMA table_info({t})")] for t in TABLES}
            n = 0
            for t in TABLES:
                have = {r["column_name"] for r in self.all("SELECT column_name FROM information_schema.columns WHERE table_name=?", (t,))}
                use = [c for c in cols[t] if c in have]
                for row in src.execute(f"SELECT {','.join(use)} FROM {t}"):
                    vals = list(row)
                    if t == "users":
                        d = dict(zip(use, vals)); d.setdefault("username_lc", (d["username"] or "").lower())
                        if "username_lc" not in use: use2 = use + ["username_lc"]; vals = vals + [d["username_lc"]]
                        else: use2 = use
                        if "role" not in use2: use2 = use2 + ["role"]; vals = vals + ["admin" if d.get("is_admin") else "student"]
                        self.run(f"INSERT INTO users({','.join(use2)}) VALUES({','.join('?' * len(use2))}) ON CONFLICT DO NOTHING", vals)
                    else:
                        self.run(f"INSERT INTO {t}({','.join(use)}) VALUES({','.join('?' * len(use))}) ON CONFLICT DO NOTHING", vals)
                    n += 1
            self.run("SELECT setval(pg_get_serial_sequence('users','id'), (SELECT COALESCE(MAX(id),1) FROM users))")
            print(f"[store] copied {n} rows from the local SQLite file into PostgreSQL (Supabase).")
        except Exception as e:
            print("[store] SQLite import skipped:", e)
